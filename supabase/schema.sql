-- METEORA telemetry table. Run this in Supabase SQL Editor.
create table if not exists public.meteora_telemetry (
  id bigint generated by default as identity primary key,
  device_id text not null default 'METEORA-001',
  event_type text not null check (event_type in ('heartbeat','data')),
  wifi_connected boolean not null default false,
  device_on boolean not null default true,
  temperature double precision,
  humidity double precision,
  wind_speed double precision,
  oxygen double precision,
  latitude double precision,
  longitude double precision,
  created_at timestamptz not null default now()
);
create index if not exists meteora_telemetry_device_created_idx
  on public.meteora_telemetry (device_id, created_at desc);
-- Keep table private. The Next.js server uses the service-role key; ESP32 uses API token.
alter table public.meteora_telemetry enable row level security;
